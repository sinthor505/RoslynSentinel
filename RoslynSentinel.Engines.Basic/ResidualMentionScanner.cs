using System.Text.RegularExpressions;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

using RoslynSentinel.Common;

namespace RoslynSentinel.Engines.Basic;

/// <summary>
/// Post-rename scan for leftover mentions of a renamed symbol that Roslyn's renamer did not (and, with
/// RenameInComments/RenameInStrings off, deliberately does not) rewrite. Exactly what is scanned:
/// <list type="bullet">
/// <item>Every project .cs document of the post-rename solution, except generated ones: a path under a
/// skipped directory, a name ending .g.cs, .g.i.cs, .designer.cs, .AssemblyInfo.cs or
/// .AssemblyAttributes.cs, or one whose first lines contain "&lt;auto-generated".</item>
/// <item>Git-tracked non-source files under the solution root with extension .csproj, .props, .targets, .json, .md,
/// .ps1, .slnx or .sln (read from disk; unreadable files and files over 5 MB are skipped). The solution root is
/// walked instead when it is not a git repository or nothing under it is tracked.</item>
/// <item>Skipped directories (anywhere in a path below the solution root): bin, obj, .git, .roslynsentinel,
/// Worktree, node_modules (names compared case-insensitively).</item>
/// </list>
/// Each file is read once (a .cs document linked into several projects is deduplicated by full path,
/// case-insensitive). A line yields at most one mention; the first match on the line decides its bucket.
/// <para>
/// Boundary rule. A non-namespace symbol matches its simple name as a whole word (<c>\bName\b</c>, case-sensitive).
/// A namespace matches its full OLD qualified name as a dotted token: not preceded by an identifier char
/// (letter, digit, underscore), not preceded by "&lt;identchar&gt;." (so it is never the tail of a longer
/// qualified name such as X.Old.Ns), and not followed by an identifier char (Old.NsX does not match);
/// a following ".Sub" does match (Old.Ns.Sub).
/// </para>
/// <para>
/// Buckets, by precedence on the match start position: PathLike if the match is immediately followed by
/// '/' or '\' (any file type); else NonSource if the file is not .cs; else for .cs, Comment if the position
/// lies in comment trivia (single-line, multi-line, doc comments), String if it lies in a string, char,
/// interpolated-string-text, raw-string or utf8 literal token, else Code.
/// </para>
/// </summary>
public static class ResidualMentionScanner
{
    private const int MaxNonSourceBytes = 5_000_000;
    private const int AutoGeneratedHeaderLines = 10;

    private static readonly string[] NonSourceExtensions = [".csproj", ".props", ".targets", ".json", ".md", ".ps1", ".slnx", ".sln"];

    private static readonly string[] SkippedDirectoryNames = ["bin", "obj", ".git", ".roslynsentinel", "Worktree", "node_modules"];

    private static readonly string[] GeneratedFileSuffixes = [".g.cs", ".g.i.cs", ".designer.cs", ".AssemblyInfo.cs", ".AssemblyAttributes.cs"];

    /// <summary>
    /// Builds the match pattern. For a non-namespace, <paramref name="name"/> is the simple name and the pattern is a
    /// case-sensitive whole word. For a namespace, <paramref name="name"/> is the full old qualified name and the
    /// pattern is a dotted token: not preceded by an identifier char or by "identchar." and not followed by an
    /// identifier char (a following ".Sub" still matches). Identifier chars are [A-Za-z0-9_].
    /// </summary>
    public static Regex BuildPattern(string name, bool isNamespace)
    {
        var escaped = Regex.Escape(name);
        var pattern = isNamespace
            ? @"(?<![A-Za-z0-9_])(?<![A-Za-z0-9_]\.)" + escaped + "(?![A-Za-z0-9_])"
            : @"\b" + escaped + @"\b";
        return new Regex(pattern, RegexOptions.CultureInvariant);
    }

    /// <summary>
    /// Scans the post-rename <paramref name="updated"/> solution plus the non-source files under
    /// <paramref name="solutionRoot"/> (see the class remarks for the exact scope, boundary rule and buckets).
    /// <paramref name="name"/> is the simple old name, or for a namespace (<paramref name="isNamespace"/>) the full old
    /// qualified name computed before the rename. IO failures on individual files or directories are swallowed;
    /// only cancellation propagates.
    /// </summary>
    public static async Task<List<ResidualMention>> ScanAsync(Solution updated, string? solutionRoot, string name, bool isNamespace, CancellationToken cancellationToken = default)
    {
        var mentions = new List<ResidualMention>();
        if (string.IsNullOrEmpty(name))
        {
            return mentions;
        }

        var pattern = BuildPattern(name, isNamespace);
        var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var project in updated.Projects)
        {
            foreach (var document in project.Documents)
            {
                var path = document.FilePath;
                if (path is null || !path.EndsWith(".cs", StringComparison.OrdinalIgnoreCase) || !seen.Add(path))
                {
                    continue;
                }

                if (IsInSkippedDirectory(path, solutionRoot) || HasGeneratedFileName(path))
                {
                    continue;
                }

                try
                {
                    var text = await document.GetTextAsync(cancellationToken);
                    if (HasAutoGeneratedHeader(text))
                    {
                        continue;
                    }

                    var content = text.ToString();
                    var matches = pattern.Matches(content);
                    if (matches.Count == 0)
                    {
                        continue;
                    }

                    var root = await document.GetSyntaxRootAsync(cancellationToken);
                    AddMentions(mentions, matches, content, text, new FilePathWrapper(path, solutionRoot), root, isCSharp: true);
                }
                catch (Exception ex) when (ex is not OperationCanceledException)
                {
                    // A document that cannot be read or parsed is skipped; the scan is advisory.
                }
            }
        }

        if (!string.IsNullOrWhiteSpace(solutionRoot) && Directory.Exists(solutionRoot))
        {
            foreach (var file in CollectNonSourceFiles(solutionRoot, cancellationToken))
            {
                if (!seen.Add(file))
                {
                    continue;
                }

                try
                {
                    if (new FileInfo(file).Length > MaxNonSourceBytes)
                    {
                        continue;
                    }

                    var content = await File.ReadAllTextAsync(file, cancellationToken);
                    var matches = pattern.Matches(content);
                    if (matches.Count == 0)
                    {
                        continue;
                    }

                    AddMentions(mentions, matches, content, SourceText.From(content), new FilePathWrapper(file, solutionRoot), null, isCSharp: false);
                }
                catch (Exception ex) when (ex is not OperationCanceledException)
                {
                    // Unreadable non-source file (locked, permissions, bad encoding): skipped.
                }
            }
        }

        return mentions;
    }

    private static bool IsSkippedDirectoryName(string name)
    {
        foreach (var skipped in SkippedDirectoryNames)
        {
            if (string.Equals(skipped, name, StringComparison.OrdinalIgnoreCase))
            {
                return true;
            }
        }

        return false;
    }

    // True when any directory segment of the path (relative to the solution root when it lies under it, else the
    // full path) is one of SkippedDirectoryNames. The file name itself is not checked.
    private static bool IsInSkippedDirectory(string fullPath, string? solutionRoot)
    {
        var relative = fullPath;
        if (!string.IsNullOrWhiteSpace(solutionRoot))
        {
            try
            {
                var candidate = Path.GetRelativePath(solutionRoot, fullPath);
                var outside = candidate == ".." || candidate.StartsWith(".." + Path.DirectorySeparatorChar, StringComparison.Ordinal) || Path.IsPathRooted(candidate);
                if (!outside)
                {
                    relative = candidate;
                }
            }
            catch (ArgumentException)
            {
                // Malformed path: fall back to checking the full path.
            }
        }

        var segments = relative.Split(['\\', '/'], StringSplitOptions.RemoveEmptyEntries);
        for (int i = 0; i < segments.Length - 1; i++)
        {
            if (IsSkippedDirectoryName(segments[i]))
            {
                return true;
            }
        }

        return false;
    }

    private static bool HasGeneratedFileName(string path)
    {
        foreach (var suffix in GeneratedFileSuffixes)
        {
            if (path.EndsWith(suffix, StringComparison.OrdinalIgnoreCase))
            {
                return true;
            }
        }

        return false;
    }

    private static bool HasAutoGeneratedHeader(SourceText text)
    {
        var count = Math.Min(AutoGeneratedHeaderLines, text.Lines.Count);
        for (int i = 0; i < count; i++)
        {
            if (text.Lines[i].ToString().Contains("<auto-generated", StringComparison.OrdinalIgnoreCase))
            {
                return true;
            }
        }

        return false;
    }

    // Tracked files only: ignored build output and scratch folders are not residual mentions. Null means walk the root instead.
    private static List<string>? TryCollectTrackedNonSourceFiles(string solutionRoot)
    {
        // The index contents under solutionRoot, relative to it, in index order (what `git ls-files -z --cached` printed), via
        // libgit2 with a CLI fallback. An unmerged path is reported once here (ls-files repeats it per merge stage); the list is
        // sorted and filtered below, so neither difference is visible.
        var relativePaths = GitReaders.Default.ListTrackedPaths(solutionRoot, TimeSpan.FromSeconds(10));
        if (relativePaths is null || relativePaths.Count == 0)
        {
            return null;
        }

        var files = new List<string>();
        foreach (var relative in relativePaths)
        {
            var path = Path.GetFullPath(Path.Combine(solutionRoot, relative));
            var extension = Path.GetExtension(path);
            if (NonSourceExtensions.Any(e => string.Equals(e, extension, StringComparison.OrdinalIgnoreCase))
                && !IsInSkippedDirectory(path, solutionRoot)
                && File.Exists(path))
            {
                files.Add(path);
            }
        }

        files.Sort(StringComparer.OrdinalIgnoreCase);
        return files;
    }

    // Walks the solution root iteratively, pruning SkippedDirectoryNames, and returns matching files sorted by path.
    // Inaccessible directories and reparse points are skipped silently.
    private static List<string> CollectNonSourceFiles(string solutionRoot, CancellationToken cancellationToken)
    {
        var tracked = TryCollectTrackedNonSourceFiles(solutionRoot);
        if (tracked is not null)
        {
            return tracked;
        }

        var files = new List<string>();
        var pending = new Stack<string>();
        pending.Push(solutionRoot);
        var options = new EnumerationOptions
        {
            IgnoreInaccessible = true,
            AttributesToSkip = FileAttributes.ReparsePoint | FileAttributes.System,
        };
        while (pending.Count > 0)
        {
            cancellationToken.ThrowIfCancellationRequested();
            var directory = pending.Pop();
            try
            {
                foreach (var subdirectory in Directory.EnumerateDirectories(directory, "*", options))
                {
                    if (!IsSkippedDirectoryName(Path.GetFileName(subdirectory)))
                    {
                        pending.Push(subdirectory);
                    }
                }

                foreach (var file in Directory.EnumerateFiles(directory, "*", options))
                {
                    var extension = Path.GetExtension(file);
                    if (NonSourceExtensions.Any(e => string.Equals(e, extension, StringComparison.OrdinalIgnoreCase)))
                    {
                        files.Add(file);
                    }
                }
            }
            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
            {
                // Directory vanished or is unreadable: skip it.
            }
        }

        files.Sort(StringComparer.OrdinalIgnoreCase);
        return files;
    }

    // Comment / String / Code by the syntax at the match start position. Disabled text and directive trivia count as Code.
    private static ResidualBucket ClassifyCSharp(SyntaxNode? root, int position)
    {
        if (root is null || position < root.FullSpan.Start || position >= root.FullSpan.End)
        {
            return ResidualBucket.Code;
        }

        var trivia = root.FindTrivia(position, findInsideTrivia: false);
        if (trivia.Kind() is SyntaxKind.SingleLineCommentTrivia
            or SyntaxKind.MultiLineCommentTrivia
            or SyntaxKind.SingleLineDocumentationCommentTrivia
            or SyntaxKind.MultiLineDocumentationCommentTrivia)
        {
            return ResidualBucket.Comment;
        }

        var token = root.FindToken(position, findInsideTrivia: false);
        if (token.Span.Contains(position) && token.Kind() is SyntaxKind.StringLiteralToken
            or SyntaxKind.CharacterLiteralToken
            or SyntaxKind.InterpolatedStringTextToken
            or SyntaxKind.SingleLineRawStringLiteralToken
            or SyntaxKind.MultiLineRawStringLiteralToken
            or SyntaxKind.Utf8StringLiteralToken
            or SyntaxKind.Utf8SingleLineRawStringLiteralToken
            or SyntaxKind.Utf8MultiLineRawStringLiteralToken)
        {
            return ResidualBucket.String;
        }

        return ResidualBucket.Code;
    }

    // One mention per line (first match on the line decides the bucket). Precedence: PathLike, NonSource, then
    // Comment/String/Code from the syntax tree for .cs.
    private static void AddMentions(List<ResidualMention> mentions, MatchCollection matches, string content, SourceText text, FilePathWrapper filePath, SyntaxNode? root, bool isCSharp)
    {
        var lastLine = -1;
        foreach (Match match in matches)
        {
            var line = text.Lines.GetLineFromPosition(match.Index);
            if (line.LineNumber == lastLine)
            {
                continue;
            }

            lastLine = line.LineNumber;
            var end = match.Index + match.Length;
            ResidualBucket bucket;
            if (end < content.Length && (content[end] == '/' || content[end] == '\\'))
            {
                bucket = ResidualBucket.PathLike;
            }
            else if (!isCSharp)
            {
                bucket = ResidualBucket.NonSource;
            }
            else
            {
                bucket = ClassifyCSharp(root, match.Index);
            }

            var rawLine = line.ToString();
            var leading = rawLine.Length - rawLine.TrimStart().Length;
            var column = Math.Max(0, match.Index - line.Start - leading);
            mentions.Add(new ResidualMention(filePath, line.LineNumber + 1, rawLine.Trim(), bucket, column));
        }
    }
}
