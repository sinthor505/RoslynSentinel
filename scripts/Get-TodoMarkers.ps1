<#
.SYNOPSIS
  Collects TODO markers from tracked code files into docs/generated/todo_markers.md.

.DESCRIPTION
  Scans git-tracked *.cs, *.ps1, *.psm1, *.csproj, *.props and *.targets files for comment markers
  ("// TODO", "# TODO", "<!-- TODO") and writes a Markdown list grouped by file. Only tracked files are
  scanned, so PlanStepRunner */Worktree/ clones, bin/obj and ModelTestingResults are excluded.
  The inline markers stay the source of truth (CLAUDE.md, Deferred issues); this list is a regenerated
  view and is never edited by hand.

.PARAMETER OutFile
  Output path. Default: docs/generated/todo_markers.md under the repo root.

.PARAMETER PassThru
  Also return the markers as objects (File, Line, Text).

.EXAMPLE
  pwsh -NoProfile -File scripts/Get-TodoMarkers.ps1
#>
[CmdletBinding()]
param(
    [string]$OutFile,
    [switch]$PassThru
)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path $PSScriptRoot -Parent
if (-not $OutFile) { $OutFile = Join-Path $repoRoot 'docs/generated/todo_markers.md' }

$extensions = @('*.cs', '*.ps1', '*.psm1', '*.csproj', '*.props', '*.targets')
$files = & git -C $repoRoot ls-files -- @extensions
if ($LASTEXITCODE -ne 0) { throw "git ls-files failed in $repoRoot (exit $LASTEXITCODE)." }

# A marker is TODO directly after a comment opener; "TODO.md" and identifiers like "TodoItem" do not match.
$pattern = '(//|#|<!--)\s*TODO\b(?!\.md)'

$markers = foreach ($relative in $files) {
    $path = Join-Path $repoRoot $relative
    if (-not (Test-Path -LiteralPath $path)) { continue }   # deleted in the working tree
    Select-String -LiteralPath $path -Pattern $pattern -CaseSensitive | ForEach-Object {
        [pscustomobject]@{
            File = $relative -replace '\\', '/'
            Line = $_.LineNumber
            Text = $_.Line.Trim()
        }
    }
}
$markers = @($markers)

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('<!-- Generated by scripts/Get-TodoMarkers.ps1; DO NOT EDIT. Regenerate with: pwsh -NoProfile -File scripts/Get-TodoMarkers.ps1 -->')
[void]$sb.AppendLine()
[void]$sb.AppendLine('# Code TODO markers')
[void]$sb.AppendLine()
$fileCount = @($markers | Select-Object -ExpandProperty File -Unique).Count
[void]$sb.AppendLine("$($markers.Count) markers in $fileCount files. Links are relative to this file.")
foreach ($group in ($markers | Group-Object File | Sort-Object Name)) {
    [void]$sb.AppendLine()
    [void]$sb.AppendLine("## $($group.Name) ($($group.Count))")
    [void]$sb.AppendLine()
    foreach ($m in $group.Group) {
        # Backticks in the marker text would break the inline code span; swap them for quotes.
        $text = $m.Text -replace '`', "'"
        [void]$sb.AppendLine("- [$($m.Line)](../../$($m.File)#L$($m.Line)) ``$text``")
    }
}

$dir = Split-Path $OutFile -Parent
if (-not (Test-Path -LiteralPath $dir)) { New-Item -ItemType Directory -Path $dir | Out-Null }
# CRLF to match the repo's uniform line endings.
[System.IO.File]::WriteAllText($OutFile, ($sb.ToString() -replace "(?<!`r)`n", "`r`n"), [System.Text.UTF8Encoding]::new($false))
Write-Host "Wrote $($markers.Count) markers from $fileCount files to $OutFile"

if ($PassThru) { $markers }
