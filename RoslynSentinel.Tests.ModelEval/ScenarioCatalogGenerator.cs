using System.Text;

using RoslynSentinel.Tests.ModelEval.ImplementationScenarios;

namespace RoslynSentinel.Tests.ModelEval;

/// <summary>
/// Renders docs/generated/modeleval_scenarios.md: one table per <see cref="EvalAxis"/> that has a scenario, listing the
/// implementation scenarios and every <see cref="ScenarioRegistry"/> definition that declares an axis (the stop family today).
/// Output uses \n line endings and ends with a newline. DTO-EXEMPT: static helper, no data type is added.
/// </summary>
internal static class ScenarioCatalogGenerator
{
    private const string Header = "<!-- Generated by ScenarioCatalogGenerator; DO NOT EDIT. Regenerate with: scripts/Generate-ArchitectureMap.ps1 -->";
    private const string TableHeader = "| Scenario | Fixture | Variants | Tests named in Done-when | Source |";
    private const string TableSeparator = "| --- | --- | --- | --- | --- |";
    private const string EvalsPrefix = "ContosoOrders.Core/Evals/";
    private const string ScenarioFolder = "RoslynSentinel.Tests.ModelEval/ImplementationScenarios/";
    private const string StopFamilyPrefix = "StopAdherence";
    private const string StopFamilyFixture = "ContosoOrders FixtureHelpers (ChainStartingFiles)";
    private const string StopFamilySource = "RoslynSentinel.Tests.Harness/StopAdherenceScenarios.cs";
    private const string ToolErrorSuffix = "ToolError";

    /// <summary>Source cell of a definition whose family this generator does not know; Step 65's test fails on it.</summary>
    internal const string SourceNotDerived = "(source not derived)";

    private const string FixtureNotDerived = "(fixture not derived)";
    private const string NoTests = "none (exempt, rule 9)";
    private const string None = "none";

    /// <summary>The catalog text.</summary>
    public static string Render()
    {
        var rows = new List<(EvalAxis Axis, string[] Cells)>();
        foreach (var scenario in ImplementationScenarioRegistry.All)
        {
            rows.Add((scenario.PrimaryAxis, ImplementationRow(scenario)));
        }

        foreach (var definition in ScenarioRegistry.All.Where(definition => definition.PrimaryAxis != EvalAxis.Unassigned))
        {
            rows.Add((definition.PrimaryAxis, DefinitionRow(definition)));
        }

        var text = new StringBuilder();
        text.Append(Header).Append('\n');
        text.Append('\n');
        text.Append("# Model-eval scenario catalog\n");

        foreach (var axis in Enum.GetValues<EvalAxis>())
        {
            var section = rows
                .Where(row => row.Axis == axis)
                .OrderBy(row => row.Cells[0], StringComparer.Ordinal)
                .ToList();
            if (section.Count == 0)
            {
                continue;
            }

            text.Append('\n');
            text.Append("## Axis:").Append(axis).Append('\n');
            text.Append('\n');
            text.Append(TableHeader).Append('\n');
            text.Append(TableSeparator).Append('\n');
            foreach (var row in section)
            {
                text.Append("| ").Append(string.Join(" | ", row.Cells.Select(EscapeCell))).Append(" |\n");
            }
        }

        return text.ToString();
    }

    private static string[] ImplementationRow(ImplementationScenario scenario)
    {
        var variants = scenario.ParkedReason is not null
            ? "parked"
            : JoinSteps(scenario.Steps, step => step.Variants?.Select(variant => variant.Name).ToList()) ?? None;
        var tests = JoinSteps(scenario.Steps, step => step.DoneWhenTests) ?? NoTests;
        return [scenario.Id, ImplementationFixture(scenario), variants, tests, ImplementationSource(scenario.Id)];
    }

    private static string[] DefinitionRow(ScenarioDefinition definition)
    {
        var isStopFamily = definition.Id.StartsWith(StopFamilyPrefix, StringComparison.Ordinal);
        var tests = definition.DoneWhenTests is { Count: > 0 } doneWhen ? string.Join(", ", doneWhen) : NoTests;
        return
        [
            definition.Id,
            isStopFamily ? StopFamilyFixture : FixtureNotDerived,
            isStopFamily ? StopFamilyVariants(definition.Id) : None,
            tests,
            isStopFamily ? StopFamilySource : SourceNotDerived,
        ];
    }

    // The stop variant and the tool-error variant name each other (same id before the ToolError suffix); the control has no sibling.
    private static string StopFamilyVariants(string id)
    {
        var baseId = StopFamilyBaseId(id);
        var siblings = ScenarioRegistry.All
            .Where(other => other.Id != id && StopFamilyBaseId(other.Id) == baseId)
            .Select(other => other.Id)
            .OrderBy(siblingId => siblingId, StringComparer.Ordinal)
            .ToList();
        return siblings.Count == 0 ? None : string.Join(", ", siblings);
    }

    private static string StopFamilyBaseId(string id) =>
        id.EndsWith(ToolErrorSuffix, StringComparison.Ordinal) ? id[..^ToolErrorSuffix.Length] : id;

    // The folder of the first seed file under ContosoOrders.Core/Evals/.
    private static string ImplementationFixture(ImplementationScenario scenario)
    {
        var key = scenario.SeedFiles.Keys.FirstOrDefault(path => path.StartsWith(EvalsPrefix, StringComparison.Ordinal));
        if (key is null)
        {
            return FixtureNotDerived;
        }

        var folder = key[EvalsPrefix.Length..].Split('/')[0];
        return EvalsPrefix + folder;
    }

    private static string ImplementationSource(string id)
    {
        var ns = ImplementationScenarioRegistry.FindScenarioClass(id)?.Namespace;
        if (ns is null)
        {
            return SourceNotDerived;
        }

        var folder = ns[(ns.LastIndexOf('.') + 1)..];
        return $"{ScenarioFolder}{folder}/{id}Scenario.cs";
    }

    // One cell over the steps: each step's items joined with ", "; a "step <k>: " prefix (steps joined with "; ") when more than one step contributes.
    private static string? JoinSteps(
        IReadOnlyList<ImplementationScenarioStep> steps,
        Func<ImplementationScenarioStep, IReadOnlyList<string>?> select)
    {
        var parts = new List<(int Step, string Text)>();
        for (var index = 0; index < steps.Count; index++)
        {
            var items = select(steps[index]);
            if (items is { Count: > 0 })
            {
                parts.Add((index + 1, string.Join(", ", items)));
            }
        }

        return parts.Count switch
        {
            0 => null,
            1 => parts[0].Text,
            _ => string.Join("; ", parts.Select(part => $"step {part.Step}: {part.Text}")),
        };
    }

    private static string EscapeCell(string cell) => cell.Replace("|", "\\|", StringComparison.Ordinal);
}
