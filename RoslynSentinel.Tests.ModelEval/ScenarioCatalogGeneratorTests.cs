using System.Text.RegularExpressions;

using RoslynSentinel.Common;
using RoslynSentinel.Tests.ModelEval.ImplementationScenarios;

namespace RoslynSentinel.Tests.ModelEval;

/// <summary>Model-free tests of <see cref="ScenarioCatalogGenerator"/> (plan_modeleval_first_slice_scenario_rework, Step 65).</summary>
[TestFixture]
public class ScenarioCatalogGeneratorTests
{
    private const int SourceColumn = 4;

    private static readonly string[] StopFamilyIds =
    [
        StopAdherenceScenarios.StopAdherenceMissingFileId,
        StopAdherenceScenarios.StopAdherenceMissingMethodId,
        StopAdherenceScenarios.StopAdherenceMissingFileToolErrorId,
        StopAdherenceScenarios.StopAdherenceMissingMethodToolErrorId,
        StopAdherenceScenarios.StopAdherenceControlId,
    ];

    // The table rows of the rendered catalog: each row's cells with the outer pipes removed and the cells trimmed (an escaped pipe stays inside its cell).
    private static List<string[]> TableRows(string markdown) =>
        markdown.Split('\n')
            .Where(line => line.StartsWith("| ", StringComparison.Ordinal))
            .Where(line => !line.StartsWith("| Scenario |", StringComparison.Ordinal) && !line.StartsWith("| --- |", StringComparison.Ordinal))
            .Select(line => Regex.Split(line[1..^1], @"(?<!\\)\|").Select(cell => cell.Trim()).ToArray())
            .ToList();

    [Test]
    public void Render_HasOneTablePerAssignedAxisInEnumOrder()
    {
        var expectedAxes = ImplementationScenarioRegistry.All.Select(scenario => scenario.PrimaryAxis)
            .Concat(ScenarioRegistry.All.Select(definition => definition.PrimaryAxis).Where(axis => axis != EvalAxis.Unassigned))
            .Distinct()
            .OrderBy(axis => (int)axis)
            .Select(axis => "## Axis:" + axis)
            .ToList();

        var markdown = ScenarioCatalogGenerator.Render();
        var headings = markdown.Split('\n').Where(line => line.StartsWith("## Axis:", StringComparison.Ordinal)).ToList();

        Assert.That(headings, Is.EqualTo(expectedAxes));
        Assert.That(markdown, Does.StartWith("<!-- Generated by ScenarioCatalogGenerator; DO NOT EDIT."));
        Assert.That(markdown, Does.EndWith("|\n"));
        Assert.That(markdown, Does.Not.Contain("\r"));
    }

    [Test]
    public void Render_ListsEveryImplementationScenarioExactlyOnce()
    {
        var ids = TableRows(ScenarioCatalogGenerator.Render()).Select(cells => cells[0]).ToList();

        Assert.That(ImplementationScenarioRegistry.All, Has.Count.EqualTo(15));
        foreach (var scenario in ImplementationScenarioRegistry.All)
        {
            Assert.That(ids.Count(id => id == scenario.Id), Is.EqualTo(1), $"{scenario.Id} must appear exactly once");
        }
    }

    [Test]
    public void Render_ListsTheFiveStopFamilyDefinitions()
    {
        var rows = TableRows(ScenarioCatalogGenerator.Render());

        Assert.That(StopFamilyIds, Has.Length.EqualTo(5));
        foreach (var id in StopFamilyIds)
        {
            Assert.That(rows.Count(cells => cells[0] == id), Is.EqualTo(1), $"{id} must appear exactly once");
        }

        // The stop variant and the tool-error variant name each other; the control has no sibling.
        var missingFile = rows.Single(cells => cells[0] == StopAdherenceScenarios.StopAdherenceMissingFileId);
        var missingFileToolError = rows.Single(cells => cells[0] == StopAdherenceScenarios.StopAdherenceMissingFileToolErrorId);
        var control = rows.Single(cells => cells[0] == StopAdherenceScenarios.StopAdherenceControlId);
        Assert.That(missingFile[2], Is.EqualTo(StopAdherenceScenarios.StopAdherenceMissingFileToolErrorId));
        Assert.That(missingFileToolError[2], Is.EqualTo(StopAdherenceScenarios.StopAdherenceMissingFileId));
        Assert.That(control[2], Is.EqualTo("none"));
    }

    [Test]
    public void Render_IsDeterministic()
    {
        var first = ScenarioCatalogGenerator.Render();
        var second = ScenarioCatalogGenerator.Render();
        Assert.That(first, Is.EqualTo(second));
    }

    [Test]
    public void Render_SourceColumn_PointsAtExistingFiles()
    {
        var repoRoot = RepoRootLocator.TryFind(AppContext.BaseDirectory)
            ?? throw new InvalidOperationException("Could not find RoslynSentinel.slnx - unable to locate repo root");

        var missing = TableRows(ScenarioCatalogGenerator.Render())
            .Select(cells => cells[SourceColumn])
            .Where(source => !File.Exists(Path.Combine(repoRoot, source.Replace('/', Path.DirectorySeparatorChar))))
            .ToList();

        Assert.That(missing, Is.Empty, "Source cells that name no file under the repo root");
    }

    [Test]
    public void Render_EveryAxisedDefinitionHasADerivedSource()
    {
        var notDerived = TableRows(ScenarioCatalogGenerator.Render())
            .Where(cells => cells[SourceColumn] == ScenarioCatalogGenerator.SourceNotDerived)
            .Select(cells => cells[0])
            .ToList();

        Assert.That(notDerived, Is.Empty, "Scenarios whose source the generator cannot derive (teach it the family)");
    }

    [Test]
    public void DoneWhenTests_AppearInTheRenderedPrompt()
    {
        var missing = new List<string>();

        foreach (var scenario in ImplementationScenarioRegistry.All)
        {
            for (var index = 0; index < scenario.Steps.Count; index++)
            {
                var step = scenario.Steps[index];
                foreach (var name in step.DoneWhenTests ?? [])
                {
                    if (!step.Prompt.Contains(name, StringComparison.Ordinal))
                    {
                        missing.Add($"{scenario.Id} step {index + 1}: {name}");
                    }
                }
            }
        }

        foreach (var definition in ScenarioRegistry.All.Where(definition => definition.DoneWhenTests is not null))
        {
            var prompt = string.Format(definition.PromptTemplate, "x");
            foreach (var name in definition.DoneWhenTests!)
            {
                if (!prompt.Contains(name, StringComparison.Ordinal))
                {
                    missing.Add($"{definition.Id}: {name}");
                }
            }
        }

        Assert.That(missing, Is.Empty, "DoneWhenTests names that do not occur in the rendered prompt");
    }
}
